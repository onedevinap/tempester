  /* ---------- Controls ---------- */
  function potBehaviour(svg, d, id, loc, groupe) {
    const val = () => (loc ? local[loc] : v[id()]);
    const ecrire = (n) => {
      if (svg.getAttribute("aria-disabled") === "true") return;
      if (loc) reglerLocal(loc, n, true);
      else regler(id(), n, groupe);
    };
    const etendue = () => (loc ? LOCAL[loc].max - LOCAL[loc].min : T[id()][1]);
    let y0 = 0,
      v0 = 0;
    svg.addEventListener("pointerdown", (e) => {
      /* No text selection while dragging; the focus is given by hand since the default is cancelled. */
      e.preventDefault();
      svg.focus({ preventScroll: true });
      y0 = e.clientY;
      v0 = val();
      svg.setPointerCapture(e.pointerId);
      if (loc && extras.onHold) extras.onHold(loc, true);
      if (!loc) toucher(id(), groupe);
    });
    for (const end of ["pointerup", "pointercancel"])
      svg.addEventListener(end, () => {
        if (loc && extras.onHold) extras.onHold(loc, false);
      });
    svg.addEventListener("pointermove", (e) => {
      if (!svg.hasPointerCapture(e.pointerId)) return;
      ecrire(v0 + Math.round(((y0 - e.clientY) * etendue()) / 150));
    });
    svg.addEventListener("dblclick", () => {
      if (!loc) regler(id(), T[id()][2], groupe);
    });
    svg.addEventListener(
      "wheel",
      (e) => {
        e.preventDefault();
        ecrire(val() + (e.deltaY < 0 ? 1 : -1));
      },
      { passive: false },
    );
    svg.addEventListener("keydown", (e) => {
      const k = { ArrowUp: 1, ArrowRight: 1, ArrowDown: -1, ArrowLeft: -1 }[
        e.key
      ];
      if (k) {
        e.preventDefault();
        ecrire(val() + k);
      }
    });
    svg.addEventListener("focus", () => {
      if (!loc) toucher(id(), groupe);
    });
    if (loc) return;
    svg.addEventListener("dragover", (e) => {
      e.preventDefault();
      d.classList.add("cible-app");
    });
    svg.addEventListener("dragleave", () =>
      d.classList.remove("cible", "cible-app"),
    );
    svg.addEventListener("drop", (e) => {
      e.preventDefault();
      d.classList.remove("cible", "cible-app");
      deposer(id());
    });
  }
  function pot(lib, f, taille, groupe) {
    const d = document.createElement("div");
    d.className = "pot" + (taille ? " " + taille : "");
    const svg = document.createElementNS(NS, "svg");
    svg.setAttribute("viewBox", "0 0 40 40");
    svg.setAttribute("tabindex", "0");
    svg.setAttribute("role", "slider");
    d.append(svg);
    if (lib)
      d.insertAdjacentHTML("beforeend", `<span class="l1">${lib}</span>`);
    const loc = typeof f === "string" ? f : null,
      id = () => (typeof f === "function" ? f() : f);
    const lire = () =>
      loc
        ? (local[loc] - LOCAL[loc].min) / (LOCAL[loc].max - LOCAL[loc].min)
        : v[id()] / T[id()][1];
    potBehaviour(svg, d, id, loc, groupe);
    if (loc === "volume") volumeKnob = svg;
    if (loc) d.title = LOCAL[loc].title;
    const unite = loc ? LOCAL[loc].unit : undefined;
    commandes.push(() => {
      if (!loc) d.dataset.param = id();
      /* The four knobs above the screen are the machine's soft knobs: encoders, whatever parameter they hold. */
      const soft = typeof f === "function";
      const pot = !soft && (loc ? POT_LOCALS.has(loc) : POT_PARAMS.has(id()));
      dessiner(svg, loc ? null : id(), lire(), pot ? undefined : encoderAt(lire()));
      svg.setAttribute("aria-label", loc ? lib : T[id()][0]);
      svg.setAttribute(
        "aria-valuetext",
        loc ? local[loc] + (unite || "") : texte(id()),
      );
      if (unite) {
        const label = d.querySelector(".l1");
        label.classList.add("dyn");
        label.textContent = local[loc] + unite;
      }
    });
    return d;
  }
  /* A control the Tempest cannot be driven by over MIDI: drawn as on the machine, but dimmed, with no effect and
     a tooltip that says why. */
  function inactif(node, message = NO_MIDI) {
    const boite = node.closest(".bt, .tb, .pot") || node;
    boite.classList.add("inactif");
    boite.title = message;
    node.title = message;
    node.setAttribute("aria-disabled", "true");
    if (node.tagName.toLowerCase() !== "button")
      node.removeAttribute("tabindex");
  }
  function reglerLocal(name, n, notify) {
    const { min, max } = LOCAL[name];
    const next = Math.max(min, Math.min(max, Math.round(n)));
    if (next === local[name]) return;
    local[name] = next;
    maj();
    if (notify && extras.onLocal) extras.onLocal(name, next);
  }
