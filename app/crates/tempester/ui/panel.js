  /* ---------- Display of a value ---------- */
  function texte(i) {
    return formatValue(i, v[i]);
  }
  /* The value `x` of parameter `i` as the Full view prints it (the Machine view prints what the machine reports). */
  function formatValue(i, x) {
    const [nom, max] = T[i];
    if (/Freq$/.test(nom) && max === 120)
      return NOTES[x % 12] + Math.floor(x / 12);
    if (/Fine/.test(nom)) return (x > 50 ? "+" : "") + (x - 50);
    if (max === 254) return (x > 127 ? "+" : "") + (x - 127);
    if (/Destination/.test(nom)) return DESTS[x];
    if (/Source/.test(nom)) return SOURCES[x];
    if (/LFO \d Shape/.test(nom)) return LFO_FORMES[x];
    if (nom === "Glide Mode") return GLIDE_MODES[x];
    if (max === 1) return x ? "On" : "Off";
    return String(x);
  }

  /* ---------- Knob drawing ---------- */
  function arc(r, a0, a1) {
    const p = (a) => [20 + r * Math.cos(a), 20 + r * Math.sin(a)];
    const [x0, y0] = p(a0),
      [x1, y1] = p(a1);
    return `M${x0.toFixed(2)} ${y0.toFixed(2)} A${r} ${r} 0 ${a1 - a0 > Math.PI ? 1 : 0} 1 ${x1.toFixed(2)} ${y1.toFixed(2)}`;
  }
  function profondeurApp(i) {
    const d = PARAM_DEST[i];
    if (d === undefined) return 0;
    let s = 0;
    for (let k = 0; k < 8; k++)
      if (v[92 + 3 * k] && v[94 + 3 * k] === d)
        s += (v[93 + 3 * k] - 127) / 127;
    return Math.max(-1, Math.min(1, s));
  }
  function anneauApp(out, a, i) {
    const prof = profondeurApp(i);
    if (!prof) return;
    const b = Math.max(A0, Math.min(A1, a + prof * (A1 - A0) * 0.5));
    out.push(
      `<path d="${arc(19.2, Math.min(a, b), Math.max(a, b) + 0.01)}" stroke="var(--anneau-app)" stroke-width="2.2" fill="none" stroke-linecap="round"/>`,
    );
  }
  /* `endless` is an encoder: no position, so no scale and no pointer. It is drawn from its turning only:
     `angle` (degrees, 0 = top, clockwise) places a bright dot on the ring, one fixed angle per detent, and the
     ring of dashes runs with it; `flash` ({from, sweep}, degrees) lights the part of the ring the last turn crossed. */
  const toRad = (deg) => ((deg - 90) * Math.PI) / 180;
  function endlessRing(endless) {
    const r = 17.2,
      out = [
        `<circle cx="20" cy="20" r="${r}" fill="none" stroke="#dfe6ee" stroke-width="1.8" stroke-dasharray="1.6 3.1" stroke-dashoffset="${(-toRad(endless.angle + 90) * r).toFixed(2)}"/>`,
      ];
    if (endless.flash) {
      const { from, sweep } = endless.flash;
      const [a, b] = sweep < 0 ? [from + sweep, from] : [from, from + sweep];
      out.push(
        `<path class="turnflash" d="${arc(r, toRad(a), toRad(b))}" stroke="#ffb340" stroke-width="3.4" fill="none" stroke-linecap="round"/>`,
      );
    }
    const dot = toRad(endless.angle);
    out.push(
      `<circle class="turndot" cx="${(20 + r * Math.cos(dot)).toFixed(2)}" cy="${(20 + r * Math.sin(dot)).toFixed(2)}" r="2.7" fill="#fffbe6" stroke="#1b1f24" stroke-width=".9"/>`,
    );
    return out;
  }
  /* The knobs that are absolute pots on the machine (Feedback, LP Freq, Resonance, Audio Mod, HP Freq, and Distort,
     Compress, Volume); every other parameter is set by an encoder there, so it is drawn as one, as in the Machine
     view, with its dot at the value. */
  const POT_PARAMS = new Set([33, 34, 35, 39, 41]);
  const POT_LOCALS = new Set(["distort", "compress", "volume"]);
  function encoderAt(x) {
    return { angle: ((A0 + (A1 - A0) * x) * 180) / Math.PI + 90, flash: null };
  }
  function dessiner(svg, i, x, endless) {
    const a = A0 + (A1 - A0) * x,
      out = [];
    if (endless) {
      out.push(...endlessRing(endless));
    } else {
      out.push(
        `<path d="${arc(17, A0, A1)}" stroke="rgba(0,0,0,.35)" stroke-width="1.6" fill="none" stroke-linecap="round"/>`,
      );
      out.push(
        `<path d="${arc(17, A0, Math.max(A0 + 0.01, a))}" stroke="#dfe6ee" stroke-width="1.6" fill="none" stroke-linecap="round"/>`,
      );
    }
    if (i !== null) anneauApp(out, a, i);
    out.push(
      `<ellipse cx="21.2" cy="23" rx="13.2" ry="12.6" fill="rgba(0,0,0,.28)"/><circle cx="20" cy="21.4" r="12.9" fill="rgba(0,0,0,.35)"/><circle cx="20" cy="21" r="12.5" fill="url(#jupe)"/><circle cx="20" cy="21" r="12.1" fill="none" stroke="rgba(255,255,255,.07)" stroke-width="1.4" stroke-dasharray="0.9 1.2"/><circle cx="20" cy="20" r="9.6" fill="url(#cap)"/><circle cx="20" cy="20" r="9.1" fill="none" stroke="rgba(255,255,255,.55)" stroke-width=".5"/>`,
    );
    if (!endless)
      out.push(
        `<line x1="${(20 + 3.5 * Math.cos(a)).toFixed(2)}" y1="${(20 + 3.5 * Math.sin(a)).toFixed(2)}" x2="${(20 + 9 * Math.cos(a)).toFixed(2)}" y2="${(20 + 9 * Math.sin(a)).toFixed(2)}" stroke="#1b1f24" stroke-width="1.8" stroke-linecap="round"/>`,
      );
    svg.innerHTML = out.join("");
  }
