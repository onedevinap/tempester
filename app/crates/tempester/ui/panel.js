  /* The 16 pads; `onPad(pad, down)` is the page's (the Machine view builds its own set with its own handler). The
     pad of a press is kept for its release, so that a bank change in between cannot leave a note on. */
  function pads(onPad) {
    const zone = document.createElement("div");
    zone.className = "sec pads";
    for (let k = 0; k < 16; k++) {
      const b = document.createElement("button");
      b.type = "button";
      b.className = "pad";
      b.dataset.led = FIRST_PAD_LED + k;
      b.innerHTML = `<span class="n">${k + 1}</span><span class="nom"></span>`;
      padButtons.push({ b, k });
      labelPad({ b, k });
      let pressed = k;
      const press = (down) => {
        b.classList.toggle("flash", down);
        if (down) pressed = k + (bankB ? padNotes.BANK : 0);
        if (onPad) onPad(pressed, down);
      };
      b.addEventListener("pointerdown", (e) => {
        e.preventDefault();
        press(true);
      });
      for (const end of ["pointerup", "pointerleave", "pointercancel"])
        b.addEventListener(end, () => {
          if (b.classList.contains("flash")) press(false);
        });
      zone.append(b);
    }
    return zone;
  }
