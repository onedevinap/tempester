  function deposer(i) {
    if (!glisse) return;
    const d = PARAM_DEST[i];
    if (d === undefined) {
      dire(`${T[i][0]} is not a destination of the Mod Paths.`);
      return;
    }
    let n = -1;
    for (let k = 0; k < 8; k++)
      if (v[92 + 3 * k] === glisse.src && v[94 + 3 * k] === d) n = k;
    if (n < 0)
      for (let k = 0; k < 8; k++)
        if (!v[92 + 3 * k]) {
          n = k;
          break;
        }
    if (n < 0) {
      dire(
        "All 8 Mod Paths are used: set the source of one to Off to free it.",
      );
      return;
    }
    regler(92 + 3 * n, glisse.src);
    regler(94 + 3 * n, d);
    regler(93 + 3 * n, 167);
    toucher(93 + 3 * n, [92 + 3 * n, 93 + 3 * n, 94 + 3 * n, i]);
    dire(`Mod Path ${n + 1}: ${SOURCES[glisse.src]} -> ${DESTS[d]}.`);
  }

