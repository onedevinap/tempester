/* Panel face of the Tempest, ported from the validated mockup Docs/mockups/tempest-panel.html (v18).
   One control per sound parameter; the parameter numbers (index, maximum, default) come from Rust, the labels from
   panel-labels.js. Identifiers keep the mockup's (French) vocabulary where they name its CSS classes.

   Tempester.panel.mount(el, params, onChange, extras)
     params   [{index, max, default}] as generated by tempest-proto
     onChange (index, value) called when the user changes a control (not when the machine does)
     extras   {onPad(pad, down), onLocal(name, value), onTransport(start), onKey(code, down), onMessage(text)} optional
              onPad: pad 0-31 (A1-B16: the Sound Bank B LED of the machine adds 16, as its key does), the same pad
              for the press and its release
              onLocal: the BPM, Distort, Compress and Volume knobs (the only ones that are not sound parameters)
              onHold(name, down): one of those knobs taken (true) or let go (false)
              onTransport: the Play (true) and Stop (false) keys (MIDI Start and Stop)
              onKey: a key of the remote panel (Tempester 1.6.0.0) pressed (true) or released (false), by key code
   Tempester.panel.setLocal(name, val)   the BPM knob moved elsewhere (the Play page)
   Tempester.panel.setValues(values)     the 127 values of a sound (sync)
   Tempester.panel.setValue(index, val)  one value (a knob turned on the machine)
   Tempester.panel.setSoundName(name)    name shown on the LCD
   Tempester.panel.setRemote(on)         the remote panel answered (or not): enables the keys and Volume
   Tempester.panel.setLeds(changes)      [[index, 0|1], ...] LED changes of the machine, mirrored on keys and pads; the
                                         Sound Bank B LED sets the bank of the pads (and their note labels)
   Tempester.panel.releaseKeys()         releases every held key
   Tempester.panel.refit()               sizes the face again (window or zoom changed; panel-view.js)
   Tempester.panel.parts                 pieces of the face that the Machine view (panel-machine.js) draws again
   Only one panel exists per page. */
