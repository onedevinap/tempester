#!/usr/bin/env python3
"""Generate the Rust tables of the Tempester app from the repository data.

usage: python3 -I tools/generate_rust_tables.py [--out <dir>] [--check]

Inputs : profile/dsi-tempest/sound_params.json (the 127 sound parameters),
         patch/*.json and versions/*.json (the Main patch recipes, Docs/patch-recipe-format.md, and the Tempester
         versions, with the SHA-256 of the image
         and of the .syx each one must build to: the app compares its own build with them, and a dump read back from
         the machine; the DSI file is never in the repository, so the reference hashes come from the manifests).
         Only the versions of kind `release` and `corrections` go into the app's table, with their date, one-line
         summary and changelog (`changes`: `fixes`, `additions`, `changes`, short sentences for musicians). The test
         builds (kind `test`: single-patch proofs and superseded intermediates) live in versions/archive/, are
         built by tools/verify.sh and never reach the app.
Outputs: <dir>/params.rs and <dir>/versions.rs, default
         app/crates/tempest-proto/src/generated/ (committed, "generated, do not edit").
--check  writes nothing and exits 1 when the committed files differ from a fresh generation
         (run by tools/verify.sh).
The generated code holds the recipes only (addresses, our literal words, copies and fields to read from the
user's own image, jump targets): no DSI byte (tools/dsi_content_guard.py checks it).
Refuses a manifest without a valid kind, date, summary or changes (a test build in versions/ and a release in
versions/archive/ too), a table without exactly one `corrections` version, a malformed recipe (tools/recipe.py), recipes over different input images, a parameter table
whose indexes are not 0..126 in order or whose fields do not fit the 128-byte sound, a version whose
sha256_image / sha256_image_written / sha256_syx is missing or is not 64 hexadecimal characters (record them with
`tools/build_version.py <manifest> <Main_1.5.0.2.bin> <folder> --record`)."""
import importlib.util
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
_spec = importlib.util.spec_from_file_location('recipe', Path(__file__).resolve().parent / 'recipe.py')
recipe = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(recipe)
DEFAULT_OUT = ROOT / 'app' / 'crates' / 'tempest-proto' / 'src' / 'generated'
HEADER = ('// @generated by tools/generate_rust_tables.py from {sources}.\n'
          '// Generated, do not edit: run `python3 -I tools/generate_rust_tables.py` instead.\n\n')
SOUND_BITS = 128 * 8
APP_KINDS = ('release', 'corrections')
KINDS = APP_KINDS + ('test',)
CHANGE_GROUPS = ('fixes', 'additions', 'changes')
RUST_KINDS = {'release': 'Release', 'corrections': 'Corrections'}
SUMMARY_MAX = 200
SENTENCE_MAX = 300


def rs_str(text: str) -> str:
    escaped = text.replace('\\', '\\\\').replace('"', '\\"').replace('\n', '\\n').replace('\r', '\\r').replace('\t', '\\t')
    return f'"{escaped}"'


def check_parameters(params: list[dict]) -> None:
    for position, p in enumerate(params):
        if p['index'] != position:
            sys.exit(f'refused: parameter {p["index"]} at position {position}')
        if p['bit'] + p['bits'] > SOUND_BITS or p['max'] >= 1 << p['bits'] or p['default'] > p['max']:
            sys.exit(f'refused: parameter {position} ({p["name"]}) does not fit its field')


def generate_params(table: dict) -> str:
    params = table['params']
    check_parameters(params)
    name = table['name']
    out = [HEADER.format(sources='profile/dsi-tempest/sound_params.json'),
           'use crate::sound::ParamDef;\n\n',
           f'pub const NAME_BYTE_OFFSET: usize = {name["byte"]};\n',
           f'pub const NAME_CHARS: usize = {name["chars"]};\n',
           f'pub const NAME_CHAR_BITS: usize = {name["bits"]};\n\n',
           f'pub static PARAMS: [ParamDef; {len(params)}] = [\n']
    for p in params:
        out.append(f'    ParamDef {{ index: {p["index"]}, name: {rs_str(p["name"])}, short: {rs_str(p["short"])}, '
                   f'group: {rs_str(p["group"])}, bits: {p["bits"]}, bit: {p["bit"]}, max: {p["max"]}, '
                   f'default: {p["default"]} }},\n')
    out.append('];\n')
    return ''.join(out)


def patch_identifier(path: Path) -> str:
    return 'P_' + re.sub(r'[^A-Za-z0-9]', '_', path.stem).upper()


def rs_op(edit: 'recipe.Edit') -> str:
    if edit.kind == 'word':
        return f'Op::Word(0x{edit.value:08x})'
    if edit.kind in ('j', 'jal'):
        return f'Op::Jump {{ target: 0x{edit.value:08x}, link: {str(edit.kind == "jal").lower()} }}'
    fields = ', '.join(f'Field {{ lo: {recipe.FIELDS[n][0]}, width: {recipe.FIELDS[n][1]}, value: 0x{v:x} }}'
                       for n, v in edit.fields.items())
    return f'Op::Copy {{ from: 0x{edit.value:08x}, set: &[{fields}] }}'


def generate_patch(path: Path, spec: dict) -> str:
    try:
        recipe.check_shape(spec, path.name)
        edits = [recipe.parse_edit(e, f'{path.name} edit {i}') for i, e in enumerate(spec['edits'])]
    except recipe.RecipeError as e:
        sys.exit(f'refused: {e}')
    rows = [f'        Edit {{ address: 0x{e.at:08x}, count: {e.count}, op: {rs_op(e)} }},\n' for e in edits]
    return (f'static {patch_identifier(path)}: Patch = Patch {{\n    name: {rs_str(spec["name"])},\n'
            f'    file: {rs_str("patch/" + path.name)},\n    input_sha256: {rs_str(spec["input_sha256"])},\n'
            f'    edits: &[\n{"".join(rows)}    ],\n}};\n\n')


def reference_hash(spec: dict, key: str) -> str:
    value = spec.get(key)
    if value is None:
        sys.exit(f'refused: versions/{spec["version"]}.json has no {key}; record it with '
                 f'tools/build_version.py versions/{spec["version"]}.json <Main_1.5.0.2.bin> <folder> --record')
    if not re.fullmatch(r'[0-9a-f]{64}', value):
        sys.exit(f'refused: versions/{spec["version"]}.json: {key} is not 64 lowercase hexadecimal characters')
    return value


def one_line(value: object, where: str, field: str, limit: int) -> str:
    if not isinstance(value, str) or not value.strip() or '\n' in value or len(value) > limit:
        sys.exit(f'refused: {where}: {field} must be one non-empty line of at most {limit} characters')
    return value


def check_changes(changes: object, where: str) -> None:
    if not isinstance(changes, dict) or not changes or not set(changes) <= set(CHANGE_GROUPS):
        sys.exit(f'refused: {where}: changes must be a non-empty object with only {", ".join(CHANGE_GROUPS)}')
    for group, sentences in changes.items():
        if not isinstance(sentences, list) or not sentences:
            sys.exit(f'refused: {where}: changes.{group} must be a non-empty list of sentences')
        for sentence in sentences:
            one_line(sentence, where, f'a sentence of changes.{group}', SENTENCE_MAX)


def check_manifest(spec: dict, where: str, archived: bool) -> None:
    """The fields the app shows (kind, date, summary, changes, details) and where the manifest may live."""
    kind = spec.get('kind')
    if kind not in KINDS:
        sys.exit(f'refused: {where}: kind must be one of {", ".join(KINDS)}')
    if (kind == 'test') != archived:
        sys.exit(f'refused: {where}: a `test` build belongs in versions/archive/, other kinds in versions/')
    if kind == 'test':
        return
    if not re.fullmatch(r'\d+(\.\d+){3}', str(spec.get('version'))):
        sys.exit(f'refused: {where}: version must be four numbers separated by dots')
    if not re.fullmatch(r'\d{4}-\d{2}-\d{2}', str(spec.get('date'))):
        sys.exit(f'refused: {where}: date must be YYYY-MM-DD')
    one_line(spec.get('summary'), where, 'summary', SUMMARY_MAX)
    check_changes(spec.get('changes'), where)
    if not isinstance(spec.get('description'), str) or not spec['description'].strip():
        sys.exit(f'refused: {where}: description (the technical details) is empty')


def rs_list(items: list[str]) -> str:
    return '&[' + ', '.join(rs_str(i) for i in items) + ']'


def load_manifests(root: Path) -> list[dict]:
    """The versions of the app's table, in file order; every manifest (archive included) is checked."""
    table = []
    for archived, folder in ((False, root / 'versions'), (True, root / 'versions' / 'archive')):
        for path in sorted(folder.glob('*.json')):
            spec = json.loads(path.read_text())
            check_manifest(spec, str(path.relative_to(root)), archived)
            if spec['kind'] in APP_KINDS:
                table.append(spec)
    numbers = [v['version'] for v in table]
    if len(set(numbers)) != len(numbers):
        sys.exit('refused: two versions of the table have the same number')
    if sum(v['kind'] == 'corrections' for v in table) != 1:
        sys.exit('refused: the table needs exactly one version of kind `corrections`')
    return table


def generate_version(spec: dict) -> str:
    refs = ', '.join('&' + patch_identifier(Path(p)) for p in spec['patches'])
    changes = ', '.join(f'{g}: {rs_list(spec["changes"].get(g, []))}' for g in CHANGE_GROUPS)
    return (f'    Version {{\n        version: {rs_str(spec["version"])},\n        name: {rs_str(spec["name"])},\n'
            f'        kind: Kind::{RUST_KINDS[spec["kind"]]},\n        date: {rs_str(spec["date"])},\n'
            f'        summary: {rs_str(spec["summary"])},\n        changes: Changes {{ {changes} }},\n'
            f'        description: {rs_str(spec["description"])},\n'
            f'        sha256_image: {rs_str(reference_hash(spec, "sha256_image"))},\n'
            f'        sha256_image_written: {rs_str(reference_hash(spec, "sha256_image_written"))},\n'
            f'        sha256_syx: {rs_str(reference_hash(spec, "sha256_syx"))},\n        patches: &[{refs}],\n    }},\n')


def generate_versions(root: Path) -> str:
    patches = sorted((root / 'patch').glob('*.json'))
    specs = {p: json.loads(p.read_text()) for p in patches}
    identifiers = [patch_identifier(p) for p in specs]
    if len(set(identifiers)) != len(identifiers):
        sys.exit('refused: two patch files give the same Rust identifier')
    origins = {s.get('input_sha256') for s in specs.values()}
    if len(origins) != 1:
        sys.exit(f'refused: patches built on different images: {sorted(origins)}')
    versions = load_manifests(root)
    out = [HEADER.format(sources='patch/*.json and versions/*.json'),
           'use crate::recipe::{Edit, Field, Op};\nuse crate::versions::{Changes, Kind, Patch, Version};\n\n',
           f'pub const MAIN_ORIGIN_SHA256: &str = {rs_str(origins.pop())};\n\n']
    # Only the recipes a version of the table uses: the ones of the archived test builds never reach the app (and an
    # unused static would not compile warning-free).
    used = {Path(p).name for v in versions for p in v['patches']}
    out += [generate_patch(p, s) for p, s in specs.items() if p.name in used]
    out.append(f'pub static VERSIONS: [Version; {len(versions)}] = [\n')
    out += [generate_version(v) for v in versions]
    out.append('];\n')
    return ''.join(out)


def main() -> None:
    args = sys.argv[1:]
    check = '--check' in args
    out_dir = Path(args[args.index('--out') + 1]) if '--out' in args else DEFAULT_OUT
    table = json.loads((ROOT / 'profile' / 'dsi-tempest' / 'sound_params.json').read_text())
    files = {'params.rs': generate_params(table), 'versions.rs': generate_versions(ROOT)}
    if check:
        stale = [n for n, text in files.items() if not (out_dir / n).is_file() or (out_dir / n).read_text() != text]
        if stale:
            sys.exit(f'refused: {", ".join(stale)} differ from a fresh generation; run tools/generate_rust_tables.py')
        print('generated tables are up to date')
        return
    out_dir.mkdir(parents=True, exist_ok=True)
    for name, text in files.items():
        (out_dir / name).write_text(text)
        print(f'wrote {out_dir / name} ({len(text)} bytes)')


if __name__ == '__main__':
    main()
