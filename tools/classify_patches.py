#!/usr/bin/env python3
"""Classify every word of the Tempester patches by provenance, and convert patches to recipes.

usage: classify_patches.py <Main_1.5.0.2.bin> [--write] [--check] [--report <out.md>] <patch.json…>

Reads each patch, either a recipe (format tempester-recipe/1, resolved on the image) or a patch in the former
{adresse, origine, new} format (the conversion entry point for a patch made on a branch older than the recipes),
and classifies every word it writes with tools/recipe_writer.py: (a) ours, (a=) ours but equal to a distinctive DSI
pair (stored as a copy), (b) DSI-derived (copy, copy + set), (c) trivial (nop, erased flash, jr ra, branches, jumps).
Prints the counts per patch.
--write   rewrites each file as its recipe (the former format is converted; a recipe is rewritten canonically).
--check   exit 1 when a recipe file is not exactly what the writer gives for its words (a hand-made literal that
          should be a copy, a stale classification), or when a file is still in the former format.
--report  writes the provenance report (counts per patch, every (b) and (a=) edit, no DSI byte) to <out.md>.
The image must be DSI Main 1.5.0.2 (SHA-256 checked against each patch). Writes nothing else; sends nothing."""
import importlib.util
import json
import sys
from collections import Counter
from pathlib import Path

_spec = importlib.util.spec_from_file_location('recipe_writer', Path(__file__).resolve().parent / 'recipe_writer.py')
writer = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(writer)
recipe = writer.recipe
CLASSES = ('a', 'a=', 'b', 'c')


def former_words(spec: dict, image: 'writer.Image', name: str) -> tuple[list, dict]:
    """Words and head of a patch in the former format, whose origin bytes are checked against the image."""
    if spec.get('sha256_origine') != image.sha256:
        raise recipe.RecipeError(f'{name}: built on another image than the one given')
    words = []
    for m in spec['modifications']:
        address = int(m['adresse'], 16)
        if image.at(address).to_bytes(4, 'little').hex() != m['origine']:
            raise recipe.RecipeError(f'{name}: {m["adresse"]} does not hold the declared origin word')
        why = ' ; '.join(t for t in (m.get('instruction'), m.get('raison')) if t)
        words.append(writer.Word(address, int.from_bytes(bytes.fromhex(m['new']), 'little'), why))
    head = {'name': spec['nom'], 'image': spec['image'], 'explanation': spec['explication']}
    head.update({k: v for k, v in spec.items()
                 if k not in ('nom', 'image', 'explication', 'sha256_origine', 'modifications')})
    return words, head


def recipe_words(spec: dict, image: 'writer.Image', name: str) -> tuple[list, dict]:
    whys = {}
    for edit in spec['edits']:
        for address, _ in recipe.edit_words(edit, image.data, name):
            whys[address] = edit.get('why', '')
    words = [writer.Word(a, v, whys[a]) for a, v in recipe.resolve(spec, image.data, name)]
    head = {k: v for k, v in spec.items() if k not in ('format', 'input_sha256', 'edits')}
    return words, head


def classify_file(path: Path, image: 'writer.Image') -> tuple[dict, list, bool, bool]:
    spec = json.loads(path.read_text())
    former = 'modifications' in spec
    words, head = (former_words if former else recipe_words)(spec, image, path.name)
    out, items = writer.encode(image, words, head, strip=former)
    canonical = not former and recipe.dump(out) == path.read_text()
    return out, items, former, canonical


def edit_line(edit: dict, items: dict) -> str:
    count = edit.get('count', 1)
    first = int(edit['at'], 16)
    span = f'{first:#010x}' + (f'-{first + 4 * count - 4:#010x}' if count > 1 else '')
    item = items[first]
    op = f'copy of {edit["copy"]}' + (f' ({count} words)' if count > 1 else '')
    if 'set' in edit:
        op += ', set ' + ', '.join(f'{k} = {v:#x}' for k, v in edit['set'].items())
    why = edit.get('why', '').replace('|', '/')
    return f'| {span} | {item.cls} | {item.rule} | {op} | {why} |'


def report(rows: list[tuple[str, Counter, list[dict], dict]]) -> str:
    total = Counter()
    lines = ['# Patch provenance', '',
             'Generated by `tools/classify_patches.py --report` from `patch/*.json` and the DSI Main 1.5.0.2 image '
             '(never in the repository). Classes and rules: `tools/recipe_writer.py` and '
             '`Docs/patch-recipe-format.md`. No DSI byte is quoted: a derived word is named by the address it is '
             'read from.', '',
             '- **a**: ours, literal; **a=**: ours, but equal to a distinctive DSI pair, stored as a copy;',
             '- **b**: DSI-derived, stored as a copy (relocated or moved) or a copy with one field set;',
             '- **c**: trivial, literal (nop, erased flash, jr ra, constant loads, register moves, stack-frame slots, '
             'our conditional branches), or a j / jal computed from its target.',
             '', 'Reading the counts:', '',
             '- (b) is an upper bound: a word one instruction field away from the DSI word it replaces in place, or '
             'from a word of the rewritten routine, is counted as derived even when it was written anew (n°2a-2d '
             'frames, the version numbers, the in-place rewrites of n°7d and n°15);',
             '- a trivial word is (c) whoever wrote it, including a displaced DSI instruction replayed in a trampoline '
             'when that instruction is trivial (e.g. `addiu sp,sp,-0x20`, `sw s1,0x14(sp)`): such a word only encodes '
             'a constant, a register copy or a frame slot;',
             '- a j / jal is (c) and written as its target, also when it is a copied DSI call;',
             '- the literal words of the recipes (a, c) contain no distinctive pair of DSI words: '
             '`tools/dsi_content_guard.py` checks it on every recipe.',
             '', '## Counts', '', '| Patch | words | a | a= | b | c |', '|---|---:|---:|---:|---:|---:|']
    for name, counts, _, _ in rows:
        total.update(counts)
        lines.append(f'| `{name}` | {sum(counts.values())} | ' + ' | '.join(str(counts[c]) for c in CLASSES) + ' |')
    lines.append(f'| **total** | {sum(total.values())} | ' + ' | '.join(str(total[c]) for c in CLASSES) + ' |')
    lines += ['', '## Every derived word (b) and every stored-as-copy word (a=)', '',
              'One line per edit; a run of copied words is one line with its address range.', '']
    for name, counts, edits, items in rows:
        listed = [e for e in edits if items[int(e['at'], 16)].cls in ('b', 'a=')]
        if not listed:
            continue
        lines += [f'### `{name}`', '', '| Address | class | rule | operation | why |', '|---|---|---|---|---|']
        lines += [edit_line(e, items) for e in listed]
        lines.append('')
    return '\n'.join(lines).rstrip() + '\n'


def main() -> None:
    args = sys.argv[1:]
    flags = {a for a in args if a in ('--write', '--check')}
    out_md = args[args.index('--report') + 1] if '--report' in args else None
    files = [Path(a) for a in args if a not in flags and a != '--report' and a != out_md]
    image = writer.Image(files.pop(0).read_bytes())
    rows, bad = [], []
    for path in sorted(files, key=lambda p: p.name):
        out, items, former, canonical = classify_file(path, image)
        counts = Counter(i.cls for i in items)
        rows.append((path.name, counts, out['edits'], {i.word.address: i for i in items}))
        print(f'{path.name}: {sum(counts.values())} words, ' + ', '.join(f'{c} {counts[c]}' for c in CLASSES)
              + (' (former format)' if former else '') + ('' if canonical or former else ' (not canonical)'))
        if '--write' in flags:
            path.write_text(recipe.dump(out))
        elif not canonical:
            bad.append(path.name)
    if out_md:
        Path(out_md).write_text(report(rows))
        print(f'wrote {out_md}')
    if '--check' in flags and bad:
        sys.exit(f'refused: {len(bad)} files are not canonical recipes: {", ".join(bad)}')


if __name__ == '__main__':
    main()
